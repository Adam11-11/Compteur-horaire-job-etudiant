-- 1. Colonnes attendues sur la table `shifts`
CREATE TABLE IF NOT EXISTS public.shifts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now() NOT NULL,
  date date NOT NULL,
  note text DEFAULT '',
  std_start text DEFAULT '',
  std_end text DEFAULT '',
  std_break integer DEFAULT 0,
  std_minutes integer DEFAULT 0,
  std_pay numeric DEFAULT 0,
  has_delivery boolean DEFAULT false,
  del_minutes integer DEFAULT 0,
  del_pay numeric DEFAULT 0,
  total_pay numeric DEFAULT 0,
  proof_path text,
  has_proof boolean DEFAULT false,
  proof_url text,
  is_legacy boolean DEFAULT false,
  user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid()
);

ALTER TABLE public.shifts ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid();
ALTER TABLE public.shifts ADD COLUMN IF NOT EXISTS proof_path text;
ALTER TABLE public.shifts ADD COLUMN IF NOT EXISTS has_proof boolean DEFAULT false;
ALTER TABLE public.shifts ADD COLUMN IF NOT EXISTS proof_url text;
ALTER TABLE public.shifts ADD COLUMN IF NOT EXISTS is_legacy boolean DEFAULT false;

-- S'assurer que chaque nouvelle ligne reçoit automatiquement auth.uid() si omis
ALTER TABLE public.shifts ALTER COLUMN user_id SET DEFAULT auth.uid();

CREATE INDEX IF NOT EXISTS shifts_user_date_idx
  ON public.shifts (user_id, date DESC, created_at DESC);

-- 2. Activer RLS (Row Level Security) sur `shifts`
-- Chaque utilisateur connecté ne voit, crée, modifie et supprime QUE ses propres lignes.
ALTER TABLE public.shifts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Enable read access for all users" ON public.shifts;
DROP POLICY IF EXISTS "Enable insert for all users" ON public.shifts;
DROP POLICY IF EXISTS "Enable update for all users" ON public.shifts;
DROP POLICY IF EXISTS "Enable delete for all users" ON public.shifts;
DROP POLICY IF EXISTS "Enable all access for authenticated users" ON public.shifts;
DROP POLICY IF EXISTS "shifts_select_own" ON public.shifts;
DROP POLICY IF EXISTS "shifts_insert_own" ON public.shifts;
DROP POLICY IF EXISTS "shifts_update_own" ON public.shifts;
DROP POLICY IF EXISTS "shifts_delete_own" ON public.shifts;

CREATE POLICY "shifts_select_own"
  ON public.shifts FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "shifts_insert_own"
  ON public.shifts FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "shifts_update_own"
  ON public.shifts FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "shifts_delete_own"
  ON public.shifts FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);

-- 3. Bucket Storage PRIVÉ `proofs` + cloisonnement strict par dossier `user_id/`
INSERT INTO storage.buckets (id, name, public)
VALUES ('proofs', 'proofs', false)
ON CONFLICT (id) DO UPDATE SET public = false;

-- Supprimer les anciennes policies trop permissives (TO public)
DROP POLICY IF EXISTS "Autoriser upload photos" ON storage.objects;
DROP POLICY IF EXISTS "Autoriser lecture photos" ON storage.objects;
DROP POLICY IF EXISTS "Autoriser suppression photos" ON storage.objects;
DROP POLICY IF EXISTS "Autoriser mise a jour photos" ON storage.objects;
DROP POLICY IF EXISTS "proofs_select_own" ON storage.objects;
DROP POLICY IF EXISTS "proofs_insert_own" ON storage.objects;
DROP POLICY IF EXISTS "proofs_update_own" ON storage.objects;
DROP POLICY IF EXISTS "proofs_delete_own" ON storage.objects;

-- Lecture : dossier `user_id/...` OU ancienne photo déjà rattachée à une journée de l'utilisateur
CREATE POLICY "proofs_select_own"
  ON storage.objects FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'proofs'
    AND (
      (storage.foldername(name))[1] = auth.uid()::text
      OR EXISTS (
        SELECT 1 FROM public.shifts s
        WHERE s.user_id = auth.uid() AND s.proof_path = name
      )
    )
  );

-- Upload : uniquement dans son propre dossier `user_id/...`
CREATE POLICY "proofs_insert_own"
  ON storage.objects FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'proofs'
    AND (storage.foldername(name))[1] = auth.uid()::text
  );

-- Mise à jour : uniquement dans son propre dossier `user_id/...`
CREATE POLICY "proofs_update_own"
  ON storage.objects FOR UPDATE
  TO authenticated
  USING (
    bucket_id = 'proofs'
    AND (storage.foldername(name))[1] = auth.uid()::text
  )
  WITH CHECK (
    bucket_id = 'proofs'
    AND (storage.foldername(name))[1] = auth.uid()::text
  );

-- Suppression : ses propres photos (dossier `user_id/...` ou ancienne photo rattachée à son shift)
CREATE POLICY "proofs_delete_own"
  ON storage.objects FOR DELETE
  TO authenticated
  USING (
    bucket_id = 'proofs'
    AND (
      (storage.foldername(name))[1] = auth.uid()::text
      OR EXISTS (
        SELECT 1 FROM public.shifts s
        WHERE s.user_id = auth.uid() AND s.proof_path = name
      )
    )
  );

